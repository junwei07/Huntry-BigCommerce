#!/usr/bin/env node
// Builds the storefront scripts into generated TS modules (gitignored) that
// hold the bundles as strings, so the routes can serve them on both Vercel and
// Cloudflare without reading the filesystem at runtime. dev, build and pretest
// all run this first.
//
//   storefront-script/index.ts     -> STOREFRONT_BUNDLE      (loader, every page)
//   storefront-script/map/entry.ts -> STOREFRONT_MAP_BUNDLE  (maplibre, lazy)
//
// The storefront CSS lives in real .css files (cards.css, fullscreen.css,
// claim-ui/claim-ui.css, map/map.css) and is inlined here as strings, so the routes still need no file
// read at runtime: styles.generated.ts (loader) and map/map-assets.generated.ts
// (map, next to maplibre's own CSS).
//
// maplibre-gl@6 is ESM-only and starts a module worker from a file URL, which
// a cross-origin storefront can't do. So its worker is bundled here into one
// self-contained script and embedded as a string (map/map-assets.generated.ts);
// the map starts it from a same-origin blob URL. The CSS is embedded the same
// way.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "lib", "huntry", "storefront-script");
const maplibreDist = join(root, "node_modules", "maplibre-gl", "dist");

// The loader runs on every storefront page; the map is inlined in the server
// bundle (Cloudflare Workers caps script size), so both stay bounded.
const LOADER_BUDGET_BYTES = 60 * 1024;
const MAP_BUDGET_BYTES = 2 * 1024 * 1024;

async function bundle(entry, target) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    minify: true,
    format: "iife",
    target,
    platform: "browser",
    write: false,
    legalComments: "none",
    logLevel: "error",
  });

  return result.outputFiles[0].text;
}

const asModule = (header, exports) =>
  `// ${header} — generated by scripts/build-storefront-script.mjs, do not edit or commit.\n` +
  Object.entries(exports)
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`)
    .join("");

const workerSource = await bundle(join(maplibreDist, "maplibre-gl-worker.mjs"), "es2020");

if (!workerSource.trim()) {
  throw new Error("maplibre worker bundle is empty.");
}

await mkdir(join(dir, "map"), { recursive: true });
await writeFile(
  join(dir, "map", "map-assets.generated.ts"),
  asModule("maplibre worker and CSS", {
    WORKER_SOURCE: workerSource,
    MAPLIBRE_CSS: await readFile(join(maplibreDist, "maplibre-gl.css"), "utf8"),
    HUNTRY_MAP_CSS: await readFile(join(dir, "map", "map.css"), "utf8"),
  }),
);

await writeFile(
  join(dir, "styles.generated.ts"),
  asModule("storefront loader CSS", {
    HUNTRY_CARDS_CSS: await readFile(join(dir, "cards.css"), "utf8"),
    HUNTRY_FULLSCREEN_CSS: await readFile(join(dir, "fullscreen.css"), "utf8"),
    CLAIM_UI_CSS: await readFile(join(dir, "claim-ui", "claim-ui.css"), "utf8"),
  }),
);

const loader = await bundle(join(dir, "index.ts"), "es2018");
const map = await bundle(join(dir, "map", "entry.ts"), "es2020");

for (const [name, text, budget] of [
  ["loader", loader, LOADER_BUDGET_BYTES],
  ["map", map, MAP_BUDGET_BYTES],
]) {
  const bytes = Buffer.byteLength(text);

  console.log(`storefront ${name} bundle: ${(bytes / 1024).toFixed(1)} KB`);

  if (bytes > budget) {
    throw new Error(`storefront ${name} bundle is ${bytes} bytes, over its ${budget} byte budget.`);
  }
}

await writeFile(
  join(dir, "bundle.generated.ts"),
  asModule("storefront bundles", { STOREFRONT_BUNDLE: loader, STOREFRONT_MAP_BUNDLE: map }),
);
