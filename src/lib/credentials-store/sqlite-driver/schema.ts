// Run unconditionally on every openDatabase call — safe only because a
// local SQLite file has no concurrent, independently-deployed writers to
// race against. Not shared with Postgres, which manages schema via
// node-pg-migrate instead (see postgres-driver/migrations/).
export const CREATE_CREDENTIALS_STORE_SCHEMA = `
  CREATE TABLE IF NOT EXISTS stores (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    store_hash TEXT NOT NULL UNIQUE,
    access_token TEXT NOT NULL,
    scope TEXT NOT NULL,
    admin_user_id INTEGER NOT NULL
  );

  CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER PRIMARY KEY,
    email TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS store_users (
    store_hash TEXT NOT NULL,
    user_id INTEGER NOT NULL,
    PRIMARY KEY (store_hash, user_id)
  );

  -- One row per store (only one extension is ever registered per install).
  -- extension_id is BigCommerce's own opaque id, not generated by this app.
  CREATE TABLE IF NOT EXISTS store_extensions (
    store_hash TEXT PRIMARY KEY,
    extension_id TEXT NOT NULL
  );

  -- One row per store (only one storefront script is ever registered per
  -- install). script_id is BigCommerce's own opaque id, not generated by
  -- this app.
  CREATE TABLE IF NOT EXISTS store_storefront_scripts (
    store_hash TEXT PRIMARY KEY,
    script_id TEXT NOT NULL
  );

  -- One row per store (only one Huntry page is ever provisioned per
  -- install). page_id is BigCommerce's own id; created_by_app is 0 when an
  -- existing merchant-owned /huntry/ page was adopted instead of created.
  CREATE TABLE IF NOT EXISTS store_storefront_pages (
    store_hash TEXT PRIMARY KEY,
    page_id INTEGER NOT NULL,
    created_by_app INTEGER NOT NULL
  );

  -- One row per registered webhook scope, not per store — more than one
  -- webhook scope may be registered over time. hook_id is BigCommerce's own
  -- opaque id.
  CREATE TABLE IF NOT EXISTS store_webhooks (
    store_hash TEXT NOT NULL,
    scope TEXT NOT NULL,
    hook_id TEXT NOT NULL,
    PRIMARY KEY (store_hash, scope)
  );
`;
